"""Run a fixed set of questions over the loaded Parquet and write FINDINGS.md.

    python scripts/day_findings.py [--data data] [--out FINDINGS.md]

Every number in FINDINGS.md comes from this script, so it can be reproduced and re-run on more days.
"""
import argparse
import time
from pathlib import Path

import duckdb

VIEW = r"""
CREATE VIEW pv AS
SELECT wiki, title, views,
       CAST(regexp_extract(filename, 'hour=(\d+)\.parquet', 1) AS INTEGER) AS hour,
       regexp_extract(filename, 'day=([0-9-]+)', 1) AS day
FROM read_parquet('{glob}', filename=true)
"""

META = "title NOT IN ('Main_Page', '-') AND title NOT LIKE 'Special:%' AND title NOT LIKE 'Wikipedia:%' AND title NOT LIKE 'Category:%'"
MOBILE = "(wiki LIKE '%.m' OR wiki LIKE '%.m.%')"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", type=Path, default=Path("data"))
    ap.add_argument("--out", type=Path, default=Path("FINDINGS.md"))
    args = ap.parse_args()
    con = duckdb.connect()
    con.execute(VIEW.format(glob=(args.data / "parquet" / "good" / "**" / "*.parquet").as_posix()))
    timings: dict[str, float] = {}

    def q(key: str, sql: str):
        t = time.time()
        rows = con.execute(sql).fetchall()
        timings[key] = time.time() - t
        return rows

    days = q("days", "SELECT min(day), max(day), count(DISTINCT day) FROM pv")[0]
    total_rows, total_views = q("totals", "SELECT count(*), sum(views) FROM pv")[0]
    nonzero_bytes = duckdb.sql(
        f"SELECT count(*) FROM read_parquet('{(args.data / 'parquet' / 'good' / '**' / '*.parquet').as_posix()}') WHERE bytes <> 0"
    ).fetchone()[0]
    mobile = q("mobile", f"SELECT round(100.0*sum(views) FILTER (WHERE {MOBILE})/sum(views),1) FROM pv")[0][0]
    hours = q("hours", "SELECT hour, sum(views) FROM pv GROUP BY 1 ORDER BY 1")
    wikis = q("wikis", "SELECT wiki, sum(views) v FROM pv GROUP BY 1 ORDER BY v DESC LIMIT 6")
    tail = q("tail", "SELECT round(100.0*count(*) FILTER (WHERE views=1)/count(*),1), "
                     "round(100.0*sum(views) FILTER (WHERE views=1)/sum(views),1) FROM pv")[0]
    top_en = q("top_en", f"SELECT title, sum(views) v FROM pv WHERE wiki IN ('en','en.m') AND {META} "
                         "GROUP BY 1 ORDER BY v DESC LIMIT 5")
    spikes = q("spikes", f"""
        WITH h AS (SELECT title, hour, sum(views) v FROM pv WHERE wiki IN ('en','en.m') AND {META}
                   GROUP BY 1,2 HAVING sum(views) >= 2000),
             s AS (SELECT title, max(v) mx, median(v) med FROM h GROUP BY 1 HAVING count(*) >= 20)
        SELECT title, mx, med, round(mx/med,1) r FROM s ORDER BY r DESC LIMIT 3""")
    top1000 = q("top1000", """
        WITH t AS (SELECT sum(tv) v FROM (SELECT title, sum(views) tv FROM pv WHERE wiki='en'
                   GROUP BY 1 ORDER BY 2 DESC LIMIT 1000))
        SELECT round(100.0*(SELECT v FROM t)/(SELECT sum(views) FROM pv WHERE wiki='en'),1)""")[0][0]
    distinct_pairs = q("distinct", "SELECT count(*) FROM (SELECT DISTINCT wiki, title FROM pv)")[0][0]

    lo, hi = min(hours, key=lambda r: r[1]), max(hours, key=lambda r: r[1])
    L = [
        "# What one day of pageviews shows",
        "",
        f"Generated by `scripts/day_findings.py` from the loaded Parquet: {days[2]} day(s), {days[0]}"
        + (f" to {days[1]}" if days[0] != days[1] else "")
        + f", {total_rows:,} rows, {total_views:,} views. Machine and versions are in the README.",
        "",
        "**One day is not representative.** 2024-01-01 is a holiday. Treat every figure as a question for more days, not a conclusion.",
        "",
        f"- **Mobile dominates:** {mobile}% of views come from mobile wikis (codes ending in `.m`). I have not checked how Wikimedia filters automated traffic in these files.",
        f"- **A daily rhythm:** the quietest hour (UTC {lo[0]:02d}:00) has {lo[1]:,} views and the busiest ({hi[0]:02d}:00) has {hi[1]:,}, a ratio of {hi[1]/lo[1]:.1f}x.",
        "- **Biggest wikis by views:** " + ", ".join(f"`{w}` {v:,}" for w, v in wikis) + ".",
        f"- **Long tail:** {tail[0]}% of rows have exactly 1 view and carry {tail[1]}% of all views. The 1,000 most-viewed English titles hold {top1000}% of English views.",
        "- **Top English pages (excluding Main_Page and meta pages):** " + ", ".join(f"{t} ({v:,})" for t, v in top_en) + ".",
        "- **Detectable spikes** (an English page's busiest hour against its median hour, pages with at least 2,000 views in 20 or more hours): "
        + ", ".join(f"{t} ({mx:,} vs {med:,.0f}, {r}x)" for t, mx, med, r in spikes) + ".",
        f"- **A dead column:** the size field is non-zero in {nonzero_bytes:,} rows, so it carries no information.",
        f"- **Scale:** {distinct_pairs:,} distinct (wiki, page) pairs in the loaded data.",
        "",
        "## Query times on this run",
        "",
        "Warm file cache, single DuckDB connection, not controlled cold. See milestone 3 for proper timings.",
        "",
    ]
    L += [f"- `{k}`: {v:.1f} s" for k, v in timings.items()]
    args.out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
